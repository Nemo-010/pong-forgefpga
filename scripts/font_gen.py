#!/usr/bin/env python3
"""font_gen.py -- generate src/pong_font.v and check it against the reference.

The score glyphs are the well known public-domain 5x7 digit bitmaps used in
countless LED-matrix projects (the same table that ended up in Adafruit GFX's
"font5x7").  Each column is one byte, bit 0 is the top row, so the glyph is
5 columns x 7 rows.

We render them into an 8x8 cell, centring the 5 columns at x = 1..5 and
leaving row 7 empty, which is what the SSD1306 page renderer wants.

Run:  python3 scripts/font_gen.py            # writes src/pong_font.v
      python3 scripts/font_gen.py --check out/font_dump.txt
"""

from __future__ import annotations

import argparse
import pathlib
import sys

# --------------------------------------------------------------------------
# 5 columns x 7 rows, column-major, bit0 = top row (public domain 5x7 table)
# --------------------------------------------------------------------------
FONT_5X7: dict[str, list[int]] = {
    "0": [0x3E, 0x51, 0x49, 0x45, 0x3E],
    "1": [0x00, 0x42, 0x7F, 0x40, 0x00],
    "2": [0x42, 0x61, 0x51, 0x49, 0x46],
    "3": [0x21, 0x41, 0x45, 0x4B, 0x31],
    "4": [0x18, 0x14, 0x12, 0x7F, 0x10],
    "5": [0x27, 0x45, 0x45, 0x45, 0x39],
    "6": [0x3C, 0x4A, 0x49, 0x49, 0x30],
    "7": [0x01, 0x71, 0x09, 0x05, 0x03],
    "8": [0x36, 0x49, 0x49, 0x49, 0x36],
    "9": [0x06, 0x49, 0x49, 0x29, 0x1E],
}

CELL_W = 8
CELL_H = 8
X_OFFSET = 1  # centre the 5 columns in the 8 column cell


def cell(digit: int) -> list[int]:
    """Return the 8 column bytes of the 8x8 cell for a digit."""
    glyph = FONT_5X7[str(digit)]
    cols = [0] * CELL_W
    for i, b in enumerate(glyph):
        cols[X_OFFSET + i] = b & 0x7F  # row 7 stays clear
    return cols


def render_rows(digit: int) -> list[str]:
    cols = cell(digit)
    return [
        "".join("#" if (cols[x] >> y) & 1 else "." for x in range(CELL_W))
        for y in range(CELL_H)
    ]


def dump() -> str:
    out = []
    for d in range(10):
        out.append(f"digit {d}")
        out.extend(render_rows(d))
    return "\n".join(out) + "\n"


def gen_verilog() -> str:
    lines = [
        "// pong_font.v -- 8x8 score glyphs, GENERATED by scripts/font_gen.py.",
        "// Do not edit by hand; edit the FONT_5X7 table in the generator instead.",
        "// Column-major, bit 0 = top row, glyph centred at columns 1..5.",
        "",
        "`default_nettype none",
        "",
        "module pong_font (",
        "    input  wire [3:0] digit,",
        "    input  wire [2:0] col,",
        "    input  wire [2:0] row,",
        "    output reg        pix",
        ");",
        "",
        "    reg [7:0] bmp;",
        "",
        "    always @* begin",
        '        bmp = 8\'h00;',
        "        case ({digit, col})",
    ]
    for d in range(10):
        for x, b in enumerate(cell(d)):
            if b == 0:
                continue
            lines.append(f"            7'd{d * 8 + x}: bmp = 8'h{b:02X};")
    lines += [
        "            default: bmp = 8'h00;",
        "        endcase",
        "        pix = bmp[row];",
        "    end",
        "",
        "endmodule",
        "",
        "`default_nettype wire",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="src/pong_font.v")
    ap.add_argument("--check", metavar="DUMP",
                    help="compare a simulation dump with the reference")
    args = ap.parse_args()

    if args.check:
        want = dump()
        got = pathlib.Path(args.check).read_text()
        if want != got:
            print("FONT MISMATCH", file=sys.stderr)
            print("--- expected ---"); print(want)
            print("--- got ---"); print(got)
            return 1
        print("font: simulation dump matches the generator (10 digits, 8x8)")
        return 0

    path = pathlib.Path(args.out)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(gen_verilog())
    print(f"wrote {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
